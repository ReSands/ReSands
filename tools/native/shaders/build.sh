#!/bin/sh
# Compiles the GLSL shaders to SPIR-V and embeds them in shaders_spv.h (committed, so the PC build
# needs no shader compiler). Needs glslangValidator (Homebrew glslang).
set -e
cd "$(dirname "$0")"
glslangValidator -V --target-env vulkan1.1 --vn kMeshVert -o mesh_vert.h mesh.vert
glslangValidator -V --target-env vulkan1.1 --vn kMeshFrag -o mesh_frag.h mesh.frag
# post effects (compute): GS sprite blits (haze), ColorDiffusion kernels (glow), RGBA8 <-> float
glslangValidator -V --target-env vulkan1.1 --vn kGsSpriteComp -o gs_sprite_comp.h gs_sprite.comp
glslangValidator -V --target-env vulkan1.1 --vn kColorDiffusionComp -o color_diffusion_comp.h color_diffusion.comp
glslangValidator -V --target-env vulkan1.1 --vn kRgbaFloatComp -o rgba_float_comp.h rgba_float.comp
{ echo '// Generated by tools/native/shaders/build.sh from the shaders in this folder. Do not edit.'; echo '#pragma once'; echo '#include <cstdint>';
  cat mesh_vert.h mesh_frag.h gs_sprite_comp.h color_diffusion_comp.h rgba_float_comp.h | grep -v 'pragma once'; } > ../src/shaders_spv.h
rm mesh_vert.h mesh_frag.h gs_sprite_comp.h color_diffusion_comp.h rgba_float_comp.h
