"""Writes tools/native/src/gs_tables.h: the GS memory layout tables (PSMCT32 and PSMT4) from
tools/gsvram.py and tools/gslm.py, which mirror ps2xRuntime's GS model. Run: python3 -I tools/native/gen_gs_tables.py"""
import os
import sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..'))
import gslm  # noqa: E402
import gsvram  # noqa: E402


def table(name, rows):
    ctype = 'uint16_t' if max(max(r) for r in rows) > 255 else 'uint8_t'
    body = ',\n'.join('        {' + ', '.join(str(v) for v in row) + '}' for row in rows)
    return f'    inline constexpr {ctype} {name}[{len(rows)}][{len(rows[0])}] = {{\n{body}}};\n'


out = ['// Generated by tools/native/gen_gs_tables.py from tools/gsvram.py and tools/gslm.py. Do not edit.',
       '// GS local memory layout (block and column orders) for PSMCT32 and PSMT4.',
       '#pragma once', '#include <cstdint>', '', 'namespace pop_gs', '{',
       table('kBlock32', gsvram.BLOCK), table('kColumn32', gsvram.COLUMN),
       table('kBlock4', gslm.BLOCK4), table('kColumn4', gslm.COLUMN4), '}', '']
open(os.path.join(HERE, 'src', 'gs_tables.h'), 'w').write('\n'.join(out))
print('written')
